"""Writes the Homebrew formula of the command line tool and the cask of the
app, for a published release, into a folder of a tap repository.

    scripts/release/publish_homebrew.py <version> <folder>

The files carry the release's files, as named in the GitHub Release the tag
points at, and their sha256 is the one of the download, which the tool checks
against the release's own SHA256SUMS while it goes, so the tap never points at
a checksum the release did not publish. The formula installs the macOS
tarball, which runs from wherever it is unpacked; the cask installs the disk
image.
"""

import hashlib
import json
import pathlib
import re
import subprocess
import sys

# The release's files the tap's files point at, as named in the GitHub
# Release.
MACOS_TARBALL = "euphoria-{version}-aarch64-apple-darwin.tar.gz"
DISK_IMAGE = "Euphoria-{version}.dmg"
CHECKSUMS = "SHA256SUMS"
BASE_URL = "https://github.com/lvndry/euphoria/releases/download/v{version}"


FORMULA = """\
# Generated by the Euphoria Release workflow; do not edit by hand.
class Euphoria < Formula
  desc "Key, BPM and energy detection for DJs, to mix in key"
  homepage "https://github.com/lvndry/euphoria"
  url "{base}/{tarball}"
  sha256 "{tarball_sha256}"
  license "GPL-3.0-or-later"

  livecheck do
    url "https://api.github.com/repos/lvndry/euphoria/releases/latest"
    regex(/\"tag_name\"\\s*:\\s*\"v(?<code>\\d+\\.\\d+\\.\\d+)\"/i)
  end

  on_arm do
    depends_on macos: :{macos}
  end

  def install
    bin.install "bin/euphoria"
    lib.install Dir["lib/*.dylib"]
  end

  test do
    system bin/"euphoria", "--version"
  end
end
"""

CASK = """\
# Generated by the Euphoria Release workflow; do not edit by hand.
cask "euphoria" do
  name "Euphoria"
  homepage "https://github.com/lvndry/euphoria"
  desc "Key, BPM and energy detection for DJs, to mix in key"
  version "{version}"
  sha256 "{dmg_sha256}"
  url "https://github.com/lvndry/euphoria/releases/download/v#{{version}}/Euphoria-#{{version}}.dmg"

  depends_on macos: :{macos}

  app "Euphoria.app"
end
"""


# Homebrew's names for macOS releases, by major version.
MACOS_NAMES = {
    11: "big_sur",
    12: "monterey",
    13: "ventura",
    14: "sonoma",
    15: "sequoia",
    26: "tahoe",
}


def minimum_macos(notes):
    """Homebrew's name of the oldest macOS the release runs on, read from the
    release notes, which state the app's LSMinimumSystemVersion."""
    match = re.search(r"macOS (\d+)(?:\.\d+)* or later", notes)
    if not match:
        raise SystemExit("the release notes do not say which macOS the app needs")
    major = int(match.group(1))
    if major not in MACOS_NAMES:
        raise SystemExit(f"macOS {major} has no Homebrew name known to this script")
    return MACOS_NAMES[major]


def asset_names(version):
    """The files the tap's files point at, for a release's version."""
    return {
        MACOS_TARBALL.format(version=version),
        DISK_IMAGE.format(version=version),
        CHECKSUMS,
    }


def parse_checksums(text):
    """The name to sha256 of the lines of a SHA256SUMS file."""
    found = {}
    for line in text.splitlines():
        if not line.strip():
            continue
        digest, name = line.split(maxsplit=1)
        found[name.strip()] = digest
    return found


def render_formula(version, tarball_sha256, macos):
    return FORMULA.format(
        macos=macos,
        base=BASE_URL.format(version=version),
        tarball=MACOS_TARBALL.format(version=version),
        version=version,
        tarball_sha256=tarball_sha256,
    )

def render_cask(version, dmg_sha256, macos):
    return CASK.format(version=version, dmg_sha256=dmg_sha256, macos=macos)


def release_assets(tag):
    """The names of the files of the GitHub Release of `tag`, and its notes."""
    result = subprocess.run(
        ["gh", "release", "view", tag, "--json", "assets,body"],
        check=False,
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        raise SystemExit(f"cannot read the release {tag}: {result.stderr.strip()}")
    release = json.loads(result.stdout)
    return {asset["name"] for asset in release["assets"]}, release["body"]


def fetch(url):
    """The bytes at a release file's URL."""
    result = subprocess.run(["curl", "-sSfL", url], check=False, capture_output=True)
    if result.returncode != 0:
        raise SystemExit(f"cannot read {url}: {result.stderr.decode().strip()}")
    return result.stdout


def download_checked(tag, version, name):
    """The sha256 of a file of a release, after checking the download against
    the checksum the release published for it."""
    base = BASE_URL.format(version=version)
    digests = parse_checksums(fetch(base + "/" + CHECKSUMS).decode("ascii"))
    if name not in digests:
        raise SystemExit(f"the checksums of {tag} have no {name}")
    digest = hashlib.sha256(fetch(base + "/" + name)).hexdigest()
    if digest != digests[name]:
        raise SystemExit(f"{name} is not the file the release {tag} published")
    return digest


def main():
    if len(sys.argv) != 3:
        print("usage: publish_homebrew.py <version> <folder>", file=sys.stderr)
        return 1
    version, folder = sys.argv[1:]
    if not re.fullmatch(r"\d+\.\d+\.\d+", version):
        raise SystemExit(f"{version} is not a YEAR.MONTH.N version")
    tag = "v" + version
    tarball = MACOS_TARBALL.format(version=version)
    disk_image = DISK_IMAGE.format(version=version)

    names, notes = release_assets(tag)
    macos = minimum_macos(notes)
    missing = asset_names(version) - names
    if missing:
        raise SystemExit(f"the release {tag} has no " + ", ".join(sorted(missing)))

    folder_path = pathlib.Path(folder)
    (folder_path / "Formula").mkdir(parents=True, exist_ok=True)
    (folder_path / "Casks").mkdir(parents=True, exist_ok=True)
    (folder_path / "Formula" / "euphoria.rb").write_text(
        render_formula(version, download_checked(tag, version, tarball), macos)
    )
    (folder_path / "Casks" / "euphoria.rb").write_text(
        render_cask(version, download_checked(tag, version, disk_image), macos)
    )
    print(f"Wrote the formula and the cask of Euphoria {version} in {folder}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
